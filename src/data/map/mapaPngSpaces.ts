export type MapaPngSpaceType = 'booth' | 'gate' | 'bathroom' | 'food' | 'service' | 'stage' | 'information'

export interface MapaPngSpace {
  code: string
  label?: string
  type: MapaPngSpaceType
  bounds: [number, number, number, number]
  points?: Array<[number, number]>
  showLabel?: boolean
  routeOrigin?: boolean
  needsReview?: boolean
}

const b = (code: string, x1: number, y1: number, x2: number, y2: number, needsReview = false): MapaPngSpace => ({
  code, type: 'booth', bounds: [x1, y1, x2, y2], needsReview
})
const s = (code: string, label: string, type: MapaPngSpaceType, x1: number, y1: number, x2: number, y2: number, routeOrigin = false, needsReview = false): MapaPngSpace => ({
  code, label, type, bounds: [x1, y1, x2, y2], routeOrigin, needsReview
})
const p = (code: string, label: string | undefined, type: MapaPngSpaceType, points: Array<[number, number]>, needsReview = false): MapaPngSpace => {
  const xs = points.map(point => point[0])
  const ys = points.map(point => point[1])
  return { code, label, type, points, bounds: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)], needsReview }
}
const u = (code: string, type: MapaPngSpaceType, x1: number, y1: number, x2: number, y2: number): MapaPngSpace => ({
  code, type, bounds: [x1, y1, x2, y2], showLabel: false
})

